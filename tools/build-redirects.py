#!/usr/bin/env python3
"""Generate redirects from url-map.csv. Run from the repo root after editing
url-map.csv or moving pages:

    python3 tools/build-redirects.py

Writes:
- nginx/redirects.conf  301s for nginx (the Docker image): one map per old
                        query parameter (?p=, ?cat=, ...) plus a map of old paths
- site/redirects.js     the same for static hosts without nginx (GitHub Pages);
                        loaded by site/404.html and, for ?query URLs, site/index.html
- site/404.html         "not found" page that tries redirects.js first

Checks that every new_url exists under site/ and fails if not.
"""
import csv
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(ROOT, 'site')
PARAMS = ['p', 'page_id', 'attachment_id', 'cat', 'category_name', 'tag', 'author', 'm', 'paged', 'feed']
QUERY = re.compile(r'^/(?:index\.php)?\?(%s)=([^&]+)$' % '|'.join(PARAMS))
LOADER = ('<script>if(location.search){var s=document.createElement("script");'
          's.src="/redirects.js";document.head.appendChild(s);}</script>')


def exists(url):
    return url == '/' or os.path.isfile(os.path.join(SITE, url.lstrip('/'))) or \
        os.path.isfile(os.path.join(SITE, url.strip('/'), 'index.html'))


def q(s):
    return '"%s"' % s.replace('\\', '\\\\').replace('"', '\\"')


def main():
    rows = list(csv.DictReader(open(os.path.join(ROOT, 'url-map.csv'), encoding='utf-8')))
    bad = [r for r in rows if not exists(r['new_url'])]
    for r in bad:
        print('MISSING target: %s -> %s' % (r['old_url'], r['new_url']))
    if bad:
        sys.exit(1)

    by_param = {p: {} for p in PARAMS}
    paths, js = {}, {}
    for r in rows:
        old, new = r['old_url'], r['new_url']
        m = QUERY.match(old)
        if m:
            by_param[m.group(1)][m.group(2)] = new
        else:
            paths[old] = new
            if old.endswith('/'):
                # Same folder without the slash, and as .../index.html (how the
                # initial export's own links were written).
                paths.setdefault(old.rstrip('/'), new)
                paths.setdefault(old + 'index.html', new)
                js.setdefault(old + 'index.html', new)
        if not re.search(r'\.(jpe?g|png|gif|css|js)$', old, re.I):
            js[old] = new  # images can't be redirected from a page script

    conf = ['# Generated by tools/build-redirects.py from url-map.csv; do not edit by hand.', '',
            '# Some old paths are long, and there are thousands of them.',
            'map_hash_bucket_size 256;', 'map_hash_max_size 16384;', '']
    for p in PARAMS:
        conf.append('map $arg_%s $old_%s {' % (p, p))
        conf.append('    default "";')
        conf += ['    %s %s;' % (q(k), q(v)) for k, v in sorted(by_param[p].items())]
        conf += ['}', '']
    conf.append('map $uri $old_path {')
    conf.append('    default "";')
    conf += ['    %s %s;' % (q(k), q(v)) for k, v in sorted(paths.items())]
    conf += ['}', '']
    open(os.path.join(ROOT, 'nginx', 'redirects.conf'), 'w').write('\n'.join(conf))

    script = ('// Generated by tools/build-redirects.py from url-map.csv; do not edit by hand.\n'
              '(function(){var M=%s;var l=location,p=l.pathname,q=new URLSearchParams(l.search),t;\n'
              'if(/^\\/(index\\.php)?$/.test(p)){%s.some(function(k){var v=q.get(k);'
              'return v!==null&&(t=M["/?"+k+"="+v]);});}\n'
              'if(!t)t=M[p]||M[p+"/"]||M[p.replace(/\\/$/,"")];\n'
              'if(t&&t!==p)l.replace(t+l.hash);})();\n') % (
        json.dumps(js, separators=(',', ':'), sort_keys=True), json.dumps(PARAMS))
    open(os.path.join(SITE, 'redirects.js'), 'w').write(script)

    open(os.path.join(SITE, '404.html'), 'w').write(
        '<!DOCTYPE html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
        '<title>Akimbo Comics - Page not found</title>\n<script src="/redirects.js"></script>\n'
        '</head>\n<body style="font-family:sans-serif;text-align:center;padding:4em">\n'
        '<h1>Page not found</h1>\n<p><a href="/">Go to the latest comic</a></p>\n</body>\n</html>\n')

    index = os.path.join(SITE, 'index.html')
    html = open(index, encoding='utf-8').read()
    html = re.sub(r'<script>\(function\(\)\{var m=\{.*?</script>\n?', '', html, flags=re.S)  # old inline map
    if LOADER not in html:
        html = html.replace('<head>', '<head>\n' + LOADER, 1)
    open(index, 'w', encoding='utf-8').write(html)

    print('%d mappings: %d query-string, %d path; %d in redirects.js' % (
        len(rows), sum(len(v) for v in by_param.values()), len(paths), len(js)))


if __name__ == '__main__':
    main()
